// The Worker entry point (wrangler.jsonc `main`). It wraps the one OpenNext builds and adds a short page cache in
// front of it, so a burst of visitors doesn't make the Worker render the same page again for each of them.
//
// Why: every page reads the request's host (regional pricing), so Next renders each visit in the Worker. On
// 2026-11-21 about 90 page loads in a row took the Worker over its resource limits and the whole site answered
// 500 for a minute or two. With this cache, each page is rendered about once per 5 minutes per Cloudflare
// location instead of once per visit.
//
// What is cached: GET requests for HTML and XML pages that answer 200 with no cookie set. Never the API, the
// sign-in and portal pages, Next's in-app navigation requests (RSC), or anything on workers.dev (previews),
// where Cloudflare's cache isn't available anyway.
//
// The cache key is the full address (so botlane.io and botlane.in get their own copies) plus the deployed
// version's id, so a deploy starts with an empty cache and never serves a page that points at the old build's
// scripts.

// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore `.open-next/worker.js` is generated by `opennextjs-cloudflare build`.
import {default as handler} from './.open-next/worker.js';

type Env = CloudflareEnv & {CF_VERSION_METADATA?: {id: string}};

const CACHE_SECONDS = 300;
const NEVER_CACHED = /^\/(api|account|portal)(\/|$)/;
const CACHED_TYPES = /^(text\/html|application\/xml|text\/xml)/;

function cacheable(request: Request, url: URL) {
  if (request.method !== 'GET') return false;
  if (url.hostname.endsWith('.workers.dev') || url.hostname === 'localhost') return false;
  if (NEVER_CACHED.test(url.pathname)) return false;
  // In-app navigation and server actions: Next answers these with data, not a page.
  const h = request.headers;
  if (h.has('rsc') || h.has('next-router-prefetch') || h.has('next-action') || url.searchParams.has('_rsc')) return false;
  return true;
}

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    if (!cacheable(request, url)) return handler.fetch(request, env, ctx);

    const keyUrl = new URL(url);
    keyUrl.searchParams.set('__v', env.CF_VERSION_METADATA?.id ?? 'local');
    const key = new Request(keyUrl.toString(), {method: 'GET'});
    const cache = (caches as unknown as {default: Cache}).default;

    const hit = await cache.match(key);
    if (hit) {
      const res = new Response(hit.body, hit);
      res.headers.set('x-botlane-cache', 'HIT');
      return res;
    }

    const res: Response = await handler.fetch(request, env, ctx);
    const type = res.headers.get('content-type') ?? '';
    if (res.status !== 200 || !CACHED_TYPES.test(type) || res.headers.has('set-cookie')) return res;

    const stored = new Response(res.clone().body, res);
    stored.headers.set('cache-control', `public, s-maxage=${CACHE_SECONDS}`);
    // Only full-page requests get here, so Next's Vary on its RSC headers doesn't apply to these copies.
    stored.headers.delete('vary');
    ctx.waitUntil(cache.put(key, stored));

    const out = new Response(res.body, res);
    out.headers.set('x-botlane-cache', 'MISS');
    return out;
  },
} satisfies ExportedHandler<Env>;

